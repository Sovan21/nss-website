const MONTH_NAMES = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function formatEventDateParts(dateStr) {
  if (!dateStr) return { day: "01", month: "Jan", year: "2026", monthYear: "Jan 2026" };
  const parts = dateStr.split("-");
  const year = parts[0];
  const monthIdx = parseInt(parts[1], 10) - 1;
  const day = parts[2];
  const month = MONTH_NAMES[monthIdx] || "Jan";
  return {
    day,
    month,
    year,
    monthYear: `${month} ${year}`
  };
}

/**
 * Returns upcoming events strictly on or after today's date, automatically advancing
 * to the next calendar items once a date passes.
 */
export function getUpcomingCalendarEvents(limit = 3) {
  const today = new Date();
  const todayStr = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`;
  
  // Filter events strictly today or in future
  const upcoming = CALENDAR_EVENTS.filter(evt => (evt.endDate || evt.date) >= todayStr);
  
  if (upcoming.length >= limit) {
    return upcoming.slice(0, limit);
  }
  
  // If fewer upcoming events remain in current calendar year, wrap around
  return [...upcoming, ...CALENDAR_EVENTS.filter(evt => (evt.endDate || evt.date) < todayStr)].slice(0, limit);
}

/**
 * Returns official notices dynamically based on recent/immediate NSS programs
 */
export function getDynamicNotices(limit = 3) {
  const today = new Date();
  const todayStr = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`;
  
  // Take upcoming event notice + past recent notices
  const upcoming = CALENDAR_EVENTS.filter(evt => (evt.endDate || evt.date) >= todayStr);
  const past = CALENDAR_EVENTS.filter(evt => evt.date < todayStr);
  
  const notices = [];
  
  // 1. Immediate upcoming notice (Marked "New")
  if (upcoming.length > 0) {
    const nextEvt = upcoming[0];
    notices.push({
      id: `notice-up-${nextEvt.date}`,
      date: nextEvt.date,
      title: `Notice: ${nextEvt.title}`,
      subtitle: `All NSS volunteers are requested to participate. Venue: ${nextEvt.venue || 'College Campus'}`,
      isNew: true,
      hasDoc: false
    });
  }
  
  // 2. Most recent past event reports/notices
  const recentPast = past.slice(-(limit - notices.length)).reverse();
  recentPast.forEach(evt => {
    notices.push({
      id: `notice-past-${evt.date}`,
      date: evt.date,
      title: `Report & Circular: ${evt.title}`,
      subtitle: evt.desc ? evt.desc.slice(0, 65) + "..." : `Concluded successfully at ${evt.venue || 'Campus'}.`,
      isNew: false,
      hasDoc: true
    });
  });
  
  // Fallback if not enough
  if (notices.length < limit) {
    CALENDAR_EVENTS.slice(0, limit - notices.length).forEach(evt => {
      notices.push({
        id: `notice-fb-${evt.date}`,
        date: evt.date,
        title: `Official Circular: ${evt.title}`,
        subtitle: evt.desc || "Official event notification from NSS Unit-I.",
        isNew: false,
        hasDoc: true
      });
    });
  }
  
  return notices.slice(0, limit);
}
